// ===== LANGUAGE TOGGLE =====
let currentLang = localStorage.getItem('gf-lang') || 'en';

function setLanguage(lang) {
  currentLang = lang;
  localStorage.setItem('gf-lang', lang);

  // Update all elements with data-i18n
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (translations[lang][key]) {
      el.textContent = translations[lang][key];
    }
  });

  // Update placeholders
  document.querySelectorAll('[data-i18n-ph]').forEach(el => {
    const key = el.getAttribute('data-i18n-ph');
    if (translations[lang][key]) {
      el.placeholder = translations[lang][key];
    }
  });

  // Update lang toggle buttons
  document.querySelectorAll('.lang-toggle button').forEach(btn => {
    btn.classList.toggle('active', btn.getAttribute('data-lang') === lang);
  });

  // Update html lang attribute
  document.documentElement.lang = lang;
}

// ===== MOBILE MENU =====
function initMobileMenu() {
  const hamburger = document.querySelector('.hamburger');
  const navLinks = document.querySelector('.nav-links');

  if (!hamburger || !navLinks) return;

  hamburger.addEventListener('click', () => {
    hamburger.classList.toggle('active');
    navLinks.classList.toggle('active');
  });

  // Close menu when a link is clicked
  navLinks.querySelectorAll('a').forEach(link => {
    link.addEventListener('click', () => {
      hamburger.classList.remove('active');
      navLinks.classList.remove('active');
    });
  });
}

// ===== CONDITIONAL FORM FIELDS =====
function initFormLogic() {
  const radioYes = document.getElementById('insurance-yes');
  const radioNo = document.getElementById('insurance-no');
  const conditional = document.querySelector('.conditional-fields');

  if (!radioYes || !radioNo || !conditional) return;

  function toggleConditional() {
    if (radioYes.checked) {
      conditional.classList.add('visible');
    } else {
      conditional.classList.remove('visible');
    }
  }

  radioYes.addEventListener('change', toggleConditional);
  radioNo.addEventListener('change', toggleConditional);
}

// ===== FORM SUBMISSION =====
function initFormSubmit() {
  const form = document.getElementById('quote-form');
  const thankYou = document.querySelector('.thank-you-message');

  if (!form || !thankYou) return;

  form.addEventListener('submit', (e) => {
    e.preventDefault();

    // Hide form, show thank-you
    form.style.display = 'none';
    thankYou.classList.add('visible');

    // Scroll to thank-you message
    thankYou.scrollIntoView({ behavior: 'smooth', block: 'center' });
  });
}

// ===== SMOOTH SCROLL FOR ANCHOR LINKS =====
function initSmoothScroll() {
  document.querySelectorAll('a[href^="#"]').forEach(anchor => {
    anchor.addEventListener('click', (e) => {
      const targetId = anchor.getAttribute('href');
      if (targetId === '#') return;

      const target = document.querySelector(targetId);
      if (target) {
        e.preventDefault();
        const navHeight = document.querySelector('.navbar').offsetHeight;
        const targetPos = target.getBoundingClientRect().top + window.scrollY - navHeight;
        window.scrollTo({ top: targetPos, behavior: 'smooth' });
      }
    });
  });
}

// ===== NAVBAR SHADOW ON SCROLL =====
function initNavbarScroll() {
  const navbar = document.querySelector('.navbar');
  if (!navbar) return;

  window.addEventListener('scroll', () => {
    if (window.scrollY > 50) {
      navbar.style.boxShadow = '0 2px 20px rgba(0, 0, 0, 0.12)';
    } else {
      navbar.style.boxShadow = '0 2px 10px rgba(0, 0, 0, 0.08)';
    }
  });
}

// ===== INIT =====
document.addEventListener('DOMContentLoaded', () => {
  setLanguage(currentLang);
  initMobileMenu();
  initFormLogic();
  initFormSubmit();
  initSmoothScroll();
  initNavbarScroll();
});
